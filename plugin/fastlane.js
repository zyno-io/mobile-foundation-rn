const fs = require("node:fs");
const path = require("node:path");

const { WarningAggregator, withDangerousMod } = require("expo/config-plugins");

const {
    PACKAGE,
    assertKnownKeys,
    assertOptionsObject,
    isInsideDirectory,
    isPlainObject,
    toPosixPath,
} = require("./utils");

const PLUGIN_NAME = `${PACKAGE.name}/fastlane`;
const MARKER = `Generated by ${PACKAGE.name}`;
const APPEND_FILE = "Fastfile.append";
// No default match git URL: the package is public and must not carry internal hostnames.
const MATCH_PROFILE_TYPES = ["development", "adhoc", "appstore", "enterprise"];
const GENERATED_FILES = {
    ios: ["Appfile", "Fastfile", "Matchfile", "update-match.sh", ".gitignore"],
    android: ["Appfile", "Fastfile", ".gitignore"],
};
const GITIGNORE = {
    ios: ["report.xml", "asc-api-key.json"],
    android: ["report.xml"],
};
const DEFAULT_SOURCE_DIR = {
    ios: "resources/native/ios/fastlane",
    android: "resources/native/android/fastlane",
};
const PROJECT_NAME_PATTERN = /^[A-Za-z0-9_][A-Za-z0-9_ .-]*$/;
const APPLE_TEAM_ID_PATTERN = /^[A-Z0-9]{10}$/;
const BUNDLE_ID_PATTERN = /^[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+$/;
const ANDROID_PACKAGE_PATTERN =
    /^[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+$/;
const EXTENSION_TARGET_PATTERN = /^[A-Za-z0-9-]+$/;

const IOS_KEYS = [
    "appleTeamId",
    "bundleIdentifier",
    "extensionTargets",
    "matchGitUrl",
    "matchAppIdentifiers",
    "sourceDir",
];
const ANDROID_KEYS = ["packageName", "sourceDir"];

const rubyString = (value) =>
    `"${String(value).replace(/[\\"#]/g, (c) => "\\" + c)}"`;

const rubyArray = (list) => `[${list.map(rubyString).join(", ")}]`;

const renderTemplate = (platform, name, values) => {
    const template = fs.readFileSync(
        path.join(__dirname, "templates", "fastlane", platform, name),
        "utf8",
    );
    const rendered = template.replace(/\{\{([A-Z_]+)\}\}/g, (_, key) => {
        if (!Object.prototype.hasOwnProperty.call(values, key)) {
            throw new Error(
                `${PLUGIN_NAME} template ${platform}/${name} uses unknown placeholder ${key}`,
            );
        }
        return values[key];
    });
    return rendered.replace(/\s+$/, "") + "\n";
};

const createHeader = (sourceLabel) =>
    [
        `# ${MARKER} during \`expo prebuild\`. Do not edit.`,
        `# To customize, change the plugin options or add files to ${sourceLabel}/.`,
    ].join("\n");

const appendedLanes = (text, label) =>
    text
        ? `\n# Appended from ${label}/${APPEND_FILE}\n${text.trim()}`
        : "";

const createGitignore = (platform, header) =>
    `${header}\n\n${GITIGNORE[platform].join("\n")}\n`;

const renderIosFastlane = ({
    projectName,
    bundleIdentifier,
    appleTeamId,
    extensionTargets = [],
    matchGitUrl,
    matchAppIdentifiers = {},
    sourceLabel,
    append,
}) => {
    const header = createHeader(sourceLabel);
    const commands = [];
    for (const type of MATCH_PROFILE_TYPES) {
        const ids = matchAppIdentifiers[type] ?? [];
        if (ids.length === 0) {
            continue;
        }
        const expanded = ids.flatMap((id) => [
            id,
            ...extensionTargets.map((target) => `${id}.${target}`),
        ]);
        commands.push(
            `bundle exec fastlane match ${type} -a ${expanded.join(",")}`,
        );
    }

    const values = {
        HEADER: header,
        BUNDLE_IDENTIFIER: rubyString(bundleIdentifier),
        TEAM_ID: appleTeamId
            ? `team_id(${rubyString(appleTeamId)}) # Developer Portal Team ID`
            : "# team_id is unset: set expo.ios.appleTeamId or fastlane.ios.appleTeamId.",
        GIT_URL: matchGitUrl
            ? `git_url(${rubyString(matchGitUrl)})`
            : "# git_url is unset: CI passes git_url to prepare_provisioning. For local runs, pass git_url: or set fastlane.ios.matchGitUrl.",
        XCODE_PROJECT: rubyString(projectName),
        EXTENSION_TARGETS: rubyArray(extensionTargets),
        MATCH_COMMANDS: commands.join("\n"),
        APPENDED_LANES: appendedLanes(append, sourceLabel),
    };

    const files = [
        {
            name: "Appfile",
            contents: renderTemplate("ios", "Appfile", values),
            mode: 0o644,
        },
        {
            name: "Fastfile",
            contents: renderTemplate("ios", "Fastfile", values),
            mode: 0o644,
        },
        {
            name: "Matchfile",
            contents: renderTemplate("ios", "Matchfile", values),
            mode: 0o644,
        },
    ];
    if (commands.length > 0) {
        files.push({
            name: "update-match.sh",
            contents: renderTemplate("ios", "update-match.sh", values),
            mode: 0o755,
        });
    }
    files.push({
        name: ".gitignore",
        contents: createGitignore("ios", header),
        mode: 0o644,
    });
    return files;
};

const renderAndroidFastlane = ({ packageName, sourceLabel, append }) => {
    const header = createHeader(sourceLabel);
    const values = {
        HEADER: header,
        PACKAGE_NAME: rubyString(packageName),
        APPENDED_LANES: appendedLanes(append, sourceLabel),
    };
    return [
        {
            name: "Appfile",
            contents: renderTemplate("android", "Appfile", values),
            mode: 0o644,
        },
        {
            name: "Fastfile",
            contents: renderTemplate("android", "Fastfile", values),
            mode: 0o644,
        },
        {
            name: ".gitignore",
            contents: createGitignore("android", header),
            mode: 0o644,
        },
    ];
};

const resolveSourceDir = (projectRoot, sourceDir, explicit, platform) => {
    const abs = path.resolve(projectRoot, sourceDir);
    if (isInsideDirectory(abs, path.join(projectRoot, platform))) {
        throw new Error(
            `${PLUGIN_NAME} requires sourceDir to be outside the generated ${platform}/ directory`,
        );
    }
    const label = toPosixPath(path.relative(projectRoot, abs));
    if (!fs.existsSync(abs)) {
        if (explicit) {
            throw new Error(
                `${PLUGIN_NAME} could not find the fastlane sourceDir at ${label}`,
            );
        }
        return { dir: null, label };
    }
    if (!fs.statSync(abs).isDirectory()) {
        throw new Error(
            `${PLUGIN_NAME} requires the fastlane sourceDir ${label} to be a directory`,
        );
    }
    return { dir: abs, label };
};

const listSourceEntries = (source) =>
    source.dir
        ? fs
              .readdirSync(source.dir)
              .filter((name) => name !== APPEND_FILE && name !== ".DS_Store")
        : [];

const readFastfileAppend = (source) => {
    if (!source.dir) {
        return undefined;
    }
    const appendPath = path.join(source.dir, APPEND_FILE);
    if (!fs.existsSync(appendPath)) {
        return undefined;
    }
    const text = fs.readFileSync(appendPath, "utf8");
    return text.trim() ? text : undefined;
};

const warnIos = (message) =>
    WarningAggregator.addWarningIOS("fastlane", message);
const warnAndroid = (message) =>
    WarningAggregator.addWarningAndroid("fastlane", message);

const writeFastlaneDirectory = ({ platform, outputDir, source, files }) => {
    const warn = platform === "ios" ? warnIos : warnAndroid;
    const label = source.label;
    const overrides = new Set(listSourceEntries(source));

    if (
        source.dir &&
        overrides.has("Fastfile") &&
        fs.existsSync(path.join(source.dir, APPEND_FILE))
    ) {
        throw new Error(
            `${PLUGIN_NAME} found both Fastfile and ${APPEND_FILE} in ${label}; use ${APPEND_FILE} to extend the generated Fastfile or Fastfile to replace it, not both`,
        );
    }

    fs.mkdirSync(outputDir, { recursive: true });

    // 1. Generated files, except those the source directory overrides.
    const produced = new Set();
    for (const file of files) {
        produced.add(file.name);
        if (overrides.has(file.name)) {
            continue;
        }
        const target = path.join(outputDir, file.name);
        if (fs.existsSync(target)) {
            const existing = fs.readFileSync(target, "utf8");
            if (existing !== file.contents && !existing.includes(MARKER)) {
                warn(
                    `Replaced ${platform}/fastlane/${file.name}, which foundation did not generate; to keep a custom version, add it to ${label}/`,
                );
            }
        }
        fs.writeFileSync(target, file.contents);
        fs.chmodSync(target, file.mode);
    }

    // 2. Stale generated files from an earlier run.
    for (const name of GENERATED_FILES[platform]) {
        if (produced.has(name) || overrides.has(name)) {
            continue;
        }
        const target = path.join(outputDir, name);
        if (
            fs.existsSync(target) &&
            fs.readFileSync(target, "utf8").includes(MARKER)
        ) {
            fs.rmSync(target);
        }
    }

    // 3. Source directory entries on top.
    for (const name of overrides) {
        if (GENERATED_FILES[platform].includes(name)) {
            warn(`fastlane/${name} comes from ${label}/${name} instead of the foundation template`);
        }
        fs.cpSync(path.join(source.dir, name), path.join(outputDir, name), {
            recursive: true,
            force: true,
        });
    }
};

const assertString = (value, pattern, optionName, description) => {
    if (typeof value !== "string" || !pattern.test(value)) {
        throw new Error(
            `${PLUGIN_NAME} requires ${optionName} to be ${description}`,
        );
    }
};

const assertSourceDirOption = (value, optionName) => {
    if (
        typeof value !== "string" ||
        value.trim().length === 0 ||
        /[\r\n]/.test(value)
    ) {
        throw new Error(
            `${PLUGIN_NAME} requires ${optionName} to be a non-empty string without newlines`,
        );
    }
};

const normalizeIosOptions = (raw) => {
    if (raw === false) {
        return null;
    }
    const value = raw === undefined || raw === true ? {} : raw;
    assertOptionsObject(value, "fastlane.ios", PLUGIN_NAME);
    assertKnownKeys(value, IOS_KEYS, "fastlane.ios", PLUGIN_NAME);

    if (value.appleTeamId !== undefined) {
        assertString(
            value.appleTeamId,
            APPLE_TEAM_ID_PATTERN,
            "fastlane.ios.appleTeamId",
            "a 10-character Apple team ID",
        );
    }
    if (value.bundleIdentifier !== undefined) {
        assertString(
            value.bundleIdentifier,
            BUNDLE_ID_PATTERN,
            "fastlane.ios.bundleIdentifier",
            "a valid bundle identifier",
        );
    }
    const extensionTargets = value.extensionTargets ?? [];
    if (!Array.isArray(extensionTargets)) {
        throw new Error(
            `${PLUGIN_NAME} requires fastlane.ios.extensionTargets to be an array`,
        );
    }
    for (const target of extensionTargets) {
        assertString(
            target,
            EXTENSION_TARGET_PATTERN,
            "fastlane.ios.extensionTargets entries",
            "target names containing only letters, digits, and hyphens",
        );
    }
    if (new Set(extensionTargets).size !== extensionTargets.length) {
        throw new Error(
            `${PLUGIN_NAME} requires fastlane.ios.extensionTargets to be unique`,
        );
    }
    if (value.matchGitUrl !== undefined) {
        assertString(
            value.matchGitUrl,
            /^\S+$/,
            "fastlane.ios.matchGitUrl",
            "a non-empty string without whitespace",
        );
    }
    const matchAppIdentifiers = value.matchAppIdentifiers ?? {};
    if (!isPlainObject(matchAppIdentifiers)) {
        throw new Error(
            `${PLUGIN_NAME} requires fastlane.ios.matchAppIdentifiers to be an object`,
        );
    }
    assertKnownKeys(
        matchAppIdentifiers,
        MATCH_PROFILE_TYPES,
        "fastlane.ios.matchAppIdentifiers",
        PLUGIN_NAME,
    );
    for (const [type, ids] of Object.entries(matchAppIdentifiers)) {
        if (!Array.isArray(ids)) {
            throw new Error(
                `${PLUGIN_NAME} requires fastlane.ios.matchAppIdentifiers.${type} to be an array`,
            );
        }
        for (const id of ids) {
            assertString(
                id,
                BUNDLE_ID_PATTERN,
                `fastlane.ios.matchAppIdentifiers.${type} entries`,
                "valid bundle identifiers",
            );
        }
    }
    if (value.sourceDir !== undefined) {
        assertSourceDirOption(value.sourceDir, "fastlane.ios.sourceDir");
    }

    return {
        appleTeamId: value.appleTeamId,
        bundleIdentifier: value.bundleIdentifier,
        extensionTargets,
        matchGitUrl: value.matchGitUrl,
        matchAppIdentifiers,
        sourceDir: value.sourceDir ?? DEFAULT_SOURCE_DIR.ios,
        sourceDirExplicit: value.sourceDir !== undefined,
    };
};

const normalizeAndroidOptions = (raw) => {
    if (raw === false) {
        return null;
    }
    const value = raw === undefined || raw === true ? {} : raw;
    assertOptionsObject(value, "fastlane.android", PLUGIN_NAME);
    assertKnownKeys(value, ANDROID_KEYS, "fastlane.android", PLUGIN_NAME);

    if (value.packageName !== undefined) {
        assertString(
            value.packageName,
            ANDROID_PACKAGE_PATTERN,
            "fastlane.android.packageName",
            "a valid Android package name",
        );
    }
    if (value.sourceDir !== undefined) {
        assertSourceDirOption(value.sourceDir, "fastlane.android.sourceDir");
    }

    return {
        packageName: value.packageName,
        sourceDir: value.sourceDir ?? DEFAULT_SOURCE_DIR.android,
        sourceDirExplicit: value.sourceDir !== undefined,
    };
};

const normalizeFastlaneOptions = (raw) => {
    if (raw === false) {
        return { ios: null, android: null };
    }
    const value = raw === undefined || raw === true ? {} : raw;
    assertOptionsObject(value, "fastlane", PLUGIN_NAME);
    assertKnownKeys(value, ["ios", "android"], "fastlane", PLUGIN_NAME);
    return {
        ios: normalizeIosOptions(value.ios),
        android: normalizeAndroidOptions(value.android),
    };
};

const withFastlane = (config, raw) => {
    const options = normalizeFastlaneOptions(raw);

    if (options.ios) {
        const ios = options.ios;
        config = withDangerousMod(config, [
            "ios",
            (modConfig) => {
                const { projectRoot, projectName, platformProjectRoot } =
                    modConfig.modRequest;
                if (
                    typeof projectName !== "string" ||
                    !PROJECT_NAME_PATTERN.test(projectName)
                ) {
                    throw new Error(
                        `${PLUGIN_NAME} could not determine a valid iOS project name`,
                    );
                }
                const bundleIdentifier =
                    ios.bundleIdentifier ?? modConfig.ios?.bundleIdentifier;
                assertString(
                    bundleIdentifier,
                    BUNDLE_ID_PATTERN,
                    "fastlane.ios.bundleIdentifier or expo.ios.bundleIdentifier",
                    "a valid bundle identifier",
                );
                const appleTeamId =
                    ios.appleTeamId ?? modConfig.ios?.appleTeamId;
                if (appleTeamId === undefined || appleTeamId === null) {
                    warnIos(
                        "No Apple team ID is set, so fastlane/Appfile omits team_id. Set expo.ios.appleTeamId before building with fastlane.",
                    );
                } else {
                    assertString(
                        appleTeamId,
                        APPLE_TEAM_ID_PATTERN,
                        "expo.ios.appleTeamId",
                        "a 10-character Apple team ID",
                    );
                }

                const source = resolveSourceDir(
                    projectRoot,
                    ios.sourceDir,
                    ios.sourceDirExplicit,
                    "ios",
                );
                const files = renderIosFastlane({
                    projectName,
                    bundleIdentifier,
                    appleTeamId: appleTeamId ?? undefined,
                    extensionTargets: ios.extensionTargets,
                    matchGitUrl: ios.matchGitUrl,
                    matchAppIdentifiers: ios.matchAppIdentifiers,
                    sourceLabel: source.label,
                    append: readFastfileAppend(source),
                });
                writeFastlaneDirectory({
                    platform: "ios",
                    outputDir: path.join(platformProjectRoot, "fastlane"),
                    source,
                    files,
                });
                return modConfig;
            },
        ]);
    }

    if (options.android) {
        const android = options.android;
        config = withDangerousMod(config, [
            "android",
            (modConfig) => {
                const { projectRoot, platformProjectRoot } =
                    modConfig.modRequest;
                const packageName =
                    android.packageName ?? modConfig.android?.package;
                assertString(
                    packageName,
                    ANDROID_PACKAGE_PATTERN,
                    "fastlane.android.packageName or expo.android.package",
                    "a valid Android package name",
                );
                const source = resolveSourceDir(
                    projectRoot,
                    android.sourceDir,
                    android.sourceDirExplicit,
                    "android",
                );
                const files = renderAndroidFastlane({
                    packageName,
                    sourceLabel: source.label,
                    append: readFastfileAppend(source),
                });
                writeFastlaneDirectory({
                    platform: "android",
                    outputDir: path.join(platformProjectRoot, "fastlane"),
                    source,
                    files,
                });
                return modConfig;
            },
        ]);
    }

    return config;
};

